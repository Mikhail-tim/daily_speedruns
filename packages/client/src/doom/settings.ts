/**
 * Doom run settings.
 *
 * Competitive values are locked by the event and cannot be changed here:
 * E1M1, Ultra-Violence, pistol start, the pinned shareware IWAD, and the pinned
 * engine build. Everything below is cosmetic or a control preference.
 */

import { DOOM_SKILL_ARG_ULTRA_VIOLENCE } from "@daily-speedruns/shared";

export type DoomControlPreset = "classic" | "wasd";
export type DoomPixelScaling = "crisp" | "smooth";

export interface DoomRunSettings {
  controlPreset: DoomControlPreset;
  mouseTurning: boolean;
  /** Chocolate Doom `mouse_sensitivity`, 0-9. */
  mouseSensitivity: number;
  /**"Off" launches with `-nosound`, which skips SDL audio entirely. */
  soundEnabled: boolean;
  /** Chocolate Doom `sfx_volume`, 0-15. */
  sfxVolume: number;
  /** Chocolate Doom `usegamma`, 0-4. */
  gamma: number;
  screenMelt: boolean;
  pixelScaling: DoomPixelScaling;
}

export const DEFAULT_DOOM_SETTINGS: DoomRunSettings = {
  controlPreset: "wasd",
  mouseTurning: true,
  mouseSensitivity: 5,
  soundEnabled: true,
  sfxVolume: 8,
  gamma: 0,
  screenMelt: true,
  pixelScaling: "crisp",
};

function clampInt(value: unknown, min: number, max: number, fallback: number) {
  if (typeof value !== "number" || !Number.isFinite(value)) return fallback;
  return Math.min(max, Math.max(min, Math.round(value)));
}

/** Never trust a query string: coerce whatever we get into a legal settings object. */
export function normalizeDoomSettings(raw: unknown): DoomRunSettings {
  const input = (raw && typeof raw === "object" ? raw : {}) as Partial<DoomRunSettings>;
  return {
    controlPreset: input.controlPreset === "classic" ? "classic" : "wasd",
    mouseTurning: input.mouseTurning !== false,
    mouseSensitivity: clampInt(
      input.mouseSensitivity,
      0,
      9,
      DEFAULT_DOOM_SETTINGS.mouseSensitivity
    ),
    soundEnabled: input.soundEnabled !== false,
    sfxVolume: clampInt(input.sfxVolume, 0, 15, DEFAULT_DOOM_SETTINGS.sfxVolume),
    gamma: clampInt(input.gamma, 0, 4, DEFAULT_DOOM_SETTINGS.gamma),
    screenMelt: input.screenMelt !== false,
    pixelScaling: input.pixelScaling === "smooth" ? "smooth" : "crisp",
  };
}

export function encodeDoomSettings(settings: DoomRunSettings): string {
  return encodeURIComponent(JSON.stringify(normalizeDoomSettings(settings)));
}

export function decodeDoomSettings(encoded: string | null): DoomRunSettings {
  if (!encoded) return normalizeDoomSettings({});
  try {
    return normalizeDoomSettings(JSON.parse(decodeURIComponent(encoded)));
  } catch {
    return normalizeDoomSettings({});
  }
}

/**
 * Chocolate Doom stores key bindings as **DOS scan codes**, not SDL scancodes.
 *
 * `m_config.c` keeps a `scantokey[128]` table that translates an index (the DOS
 * scan code) into the game's internal key code, so `key_up 17` means "forward =
 * the key at DOS scancode 0x11", which is W. Writing SDL scancodes here (26 for
 * W) silently binds some other key, and because it replaces the default arrow
 * binding, movement stops working entirely.
 *
 * Values below are DOS scan codes:
 *   0x11 W, 0x1E A, 0x1F S, 0x20 D
 *   0x1D Ctrl, 0x39 Space, 0x36 Right Shift
 *   0x48/0x4B/0x4D/0x50 Up/Left/Right/Down
 */
const DOS_SCANCODE = {
  A: 30,
  D: 32,
  S: 31,
  W: 17,
  SPACE: 57,
  RIGHT: 77,
  LEFT: 75,
  DOWN: 80,
  UP: 72,
  LCTRL: 29,
  RSHIFT: 54,
} as const;

function appendsKeyMap(lines: string[], settings: DoomRunSettings): void {
  if (settings.controlPreset !== "wasd") return;
  lines.push(
    `key_up ${DOS_SCANCODE.W}`,
    `key_down ${DOS_SCANCODE.S}`,
    `key_strafeleft ${DOS_SCANCODE.A}`,
    `key_straferight ${DOS_SCANCODE.D}`,
    // Keep turning on the arrow keys so a player without a mouse can still aim.
    `key_left ${DOS_SCANCODE.LEFT}`,
    `key_right ${DOS_SCANCODE.RIGHT}`,
    `key_fire ${DOS_SCANCODE.LCTRL}`,
    `key_use ${DOS_SCANCODE.SPACE}`,
    `key_speed ${DOS_SCANCODE.RSHIFT}`
  );
}

/** Contents of Chocolate Doom's main config file (`-config`). */
export function buildMainConfig(settings: DoomRunSettings): string {
  const lines = [
    "// Generated by Daily Speedruns for a timed event run.",
    "// Competitive settings are fixed; only presentation is user controlled.",
    "fullscreen 0",
    "screenblocks 10",
    "window_width 320",
    "window_height 240",
    // Chocolate Doom only reads mouse turning while the mouse is grabbed, which
    // in the browser means pointer lock. See the runtime's capture fallback:
    // when lock is refused we say so instead of leaving the player with a dead
    // mouse and no explanation.
    `grabmouse ${settings.mouseTurning ? 1 : 0}`,
    `use_mouse ${settings.mouseTurning ? 1 : 0}`,
    `mouse_sensitivity ${settings.mouseSensitivity}`,
    `sfx_volume ${settings.soundEnabled ? settings.sfxVolume : 0}`,
    "music_volume 0",
    "snd_musicdevice 0",
    ...(settings.soundEnabled ? [] : ["snd_sfxdevice 0"]),
    `screen_melt ${settings.screenMelt ? 1 : 0}`,
    `usegamma ${settings.gamma}`,
  ];
  appendsKeyMap(lines, settings);
  return `${lines.join("\n")}\n`;
}

/** Contents of Chocolate Doom's extra config file (`-extraconfig`). */
export function buildExtraConfig(): string {
  return [
    "// The web build renders reliably when the intermediate render-target",
    "// upscale path is skipped, so keep the software renderer and nearest",
    "// neighbour scaling.",
    "smooth_pixel_scaling 0",
    "force_software_renderer 1",
    "aspect_ratio_correct 1",
  ].join("\n") + "\n";
}

/** Locked engine arguments. Nothing here is derived from user input. */
export function buildEngineArgs(settings: DoomRunSettings): string[] {
  return [
    "-window",
    "-iwad",
    "/iwads/doom1.wad",
    "-config",
    "/config/default.cfg",
    "-extraconfig",
    "/config/chocolate-doom.cfg",
    "-savedir",
    "/savegames",
    "-nomusic",
    ...(settings.soundEnabled ? [] : ["-nosound"]),
    "-skill",
    String(DOOM_SKILL_ARG_ULTRA_VIOLENCE),
    "-warp",
    "1",
    "1",
    "-record",
    "/savegames/dsr-run",
  ];
}
